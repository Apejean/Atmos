/// 크레이트 안에 같이 컴파일되는 다른 코드의 라이선스(라이선스 감사 2026-10-24: dart-sys는 Dart SDK C 코드를 넣는다).
const _extraCrateFiles = <String, List<String>>{
  'dart-sys': ['dart-sdk/LICENSE'],
};

Future<void> main(List<String> args) async {
  final opt = _options(args);
  final target = opt['target']!;
  final assets = Directory(opt['flutter-assets']!);
  final out = File(opt['out']!);

  final version = _pubspecVersion();
  final registry = _registrySources();
  final engine = await _crates('rust/Cargo.toml', target, registry);
  final supervisor = await _crates('supervisor/Cargo.toml', target, registry);
  final all = [...engine, ...supervisor];
  if (engine.isEmpty) throw StateError('엔진 크레이트 목록이 비었다');

  final apache = _appendixText(all, LicenseKind.apache, preferName: 'LICENSE-APACHE');
  // symphonia 패키지(crates.io)에는 라이선스 파일이 없어, MPL 원문은 저장소에 둔 표준 원문(dbus 0.7.15의 LICENSE와 같은 파일)을 쓴다.
  final mplFile = File('tool/legal/licenses/MPL-2.0.txt');
  final mpl = mplFile.existsSync() ? _read(mplFile) : null;
  final usesApache = all.any((c) => c.chosen.contains('Apache-2.0'));
  final usesMpl = all.any((c) => c.chosen.contains('MPL-2.0'));
  if (apache == null) throw StateError('Apache License 2.0 원문을 크레이트에서 찾지 못했다');
  if (usesMpl && mpl == null) throw StateError('MPL-2.0 원문을 크레이트에서 찾지 못했다');

  final notices = _flutterNotices(assets);
  // ASIO는 Windows 판에서만 쓴다: 다른 대상에는 상표 절을 두지 않는다(ASIO 계약 3조 1항 g, 2026-10-25 사용자 결정).
  final asio = target.contains('windows');
  final b = StringBuffer()
    ..writeln('The Awesome $version - Third-party License Information')
    ..writeln('Target: $target')
    ..writeln()
    ..writeln('The Awesome includes the third-party software and data listed below. Each entry names the component, '
        'its version and the license under which it is distributed. Where a component is offered under a choice of '
        'licenses, the license named after "used under" is the one The Awesome uses.')
    ..writeln()
    ..writeln('Contents')
    ..writeln('  1. Audio engine (rust_lib_atmos_mixer_pro): ${engine.length} Rust crates')
    ..writeln('  2. Supervisor (atmos_supervisor): ${supervisor.length} Rust crates')
    ..writeln('  3. Flutter engine and Dart packages')
    ..writeln('  4. Other files distributed with the application')
    ..writeln('  5. Data');
  if (asio) b.writeln('  6. Trademarks');
  b
    ..writeln('  Appendix A. Apache License, Version 2.0')
    ..writeln(usesMpl ? '  Appendix B. Mozilla Public License, Version 2.0' : '');
  _section(b, '1. Audio engine (rust_lib_atmos_mixer_pro): ${engine.length} Rust crates');
  for (final c in engine) {
    _crateEntry(b, c);
  }
  _section(b, '2. Supervisor (atmos_supervisor): ${supervisor.length} Rust crates');
  for (final c in supervisor) {
    _crateEntry(b, c);
  }

  _section(b, '3. Flutter engine and Dart packages');
  b
    ..writeln('The following notices are generated by the Flutter tool for the Flutter engine and the Dart packages '
        'that The Awesome uses.')
    ..writeln()
    ..writeln(notices.trim());
  final dbus = _lockedVersion('dbus');
  if (dbus != null) {
    b
      ..writeln(_line)
      ..writeln('dbus $dbus: licensed under the Mozilla Public License 2.0 (text above). The Source Code Form is '
          'available at https://pub.dev/packages/dbus/versions/$dbus. The Awesome uses it unmodified.');
  }

  _section(b, '4. Other files distributed with the application');
  final usesApacheFont = _otherFiles(b, assets, opt['webview2-license']);

  _section(b, '5. Data');
  b
    ..writeln(kemarHrtfPackageName)
    ..writeln()
    ..writeln(kemarHrtfNotice);

  if (asio) {
    // 지침 15절: 제품 자료에서 "ASIO"를 처음 쓸 때 ®. 이 문서에서 ASIO가 처음 나오는 곳이 이 줄이고, 지정 상표 문장
    // 두 줄(지침 15절·계약 3조 1항 k)은 고치지 않고 그 아래에 둔다.
    _section(b, '6. Trademarks');
    b
      ..writeln('The Windows version of The Awesome uses ASIO® technology by Steinberg Media Technologies GmbH.')
      ..writeln()
      ..writeln(asioTrademarkAttribution)
      ..writeln(asioCopyrightNotice);
  }

  if (usesApache || usesApacheFont) {
    _section(b, 'Appendix A. Apache License, Version 2.0');
    b.writeln(apache.trim());
  }
  if (usesMpl) {
    _section(b, 'Appendix B. Mozilla Public License, Version 2.0');
    b.writeln(mpl!.trim());
  }

  var text = b.toString().replaceAll('\r\n', '\n');
  if (target.contains('windows')) text = text.replaceAll('\n', '\r\n');
  await out.parent.create(recursive: true);
  await out.writeAsString(text, encoding: utf8);
  stdout.writeln('engine=${engine.length} supervisor=${supervisor.length} '
      'mpl=${all.where((c) => c.chosen.contains('MPL-2.0')).length} out=${out.path} bytes=${await out.length()}');
}

Map<String, String> _options(List<String> args) {
  final o = <String, String>{};
  for (var i = 0; i + 1 < args.length; i += 2) {
    if (!args[i].startsWith('--')) throw ArgumentError('옵션 형식: --이름 값 (${args[i]})');
    o[args[i].substring(2)] = args[i + 1];
  }
  for (final k in ['target', 'flutter-assets', 'out']) {
    if (!o.containsKey(k)) throw ArgumentError('--$k가 필요하다');
  }
  return o;
}

String _pubspecVersion() {
  final m = RegExp(r'^version:\s*(\S+)', multiLine: true).firstMatch(File('pubspec.yaml').readAsStringSync());
  if (m == null) throw StateError('pubspec.yaml에 version이 없다');
  return m.group(1)!;
}

String? _lockedVersion(String package) {
  final lock = File('pubspec.lock');
  if (!lock.existsSync()) return null;
  final m = RegExp('^  $package:\\n(?:    .*\\n)*?    version: "([^"]+)"', multiLine: true)
      .firstMatch(lock.readAsStringSync().replaceAll('\r\n', '\n'));
  return m?.group(1);
}

/// 크레이트 원문이 있는 로컬 레지스트리 폴더들(CARGO_HOME, 없으면 ~/.cargo).
List<Directory> _registrySources() {
  final home = Platform.environment['CARGO_HOME'] ??
      '${Platform.environment['USERPROFILE'] ?? Platform.environment['HOME']}${Platform.pathSeparator}.cargo';
  final src = Directory('$home${Platform.pathSeparator}registry${Platform.pathSeparator}src');
  if (!src.existsSync()) throw StateError('cargo 레지스트리 원문 폴더가 없다: ${src.path}');
  return src.listSync().whereType<Directory>().toList();
}

class _Crate {
  _Crate(this.ref, this.chosen, this.files, this.repository, this.url, this.kinds, this.texts);

  final CrateRef ref;
  final List<String> chosen;

  /// 실을 파일(크레이트 폴더 기준 상대 경로)과 본문.
  final Map<String, String> files;
  final String? repository;

  /// 항목에 보일 프로젝트 주소(repository, 없으면 homepage, 없으면 crates.io).
  final String url;

  /// 크레이트 맨 위 라이선스 파일 전부의 종류와 본문(부록 원문을 찾을 때 쓴다).
  final Map<String, LicenseKind> kinds;
  final Map<String, String> texts;
}

Future<List<_Crate>> _crates(String manifest, String target, List<Directory> registry) async {
  final r = await Process.run('cargo', [
    'tree', '--manifest-path', manifest, '--target', target,
    '-e', 'normal,no-proc-macro', '--prefix', 'none', '--format', '{p}|{l}',
  ]);
  if (r.exitCode != 0) throw StateError('cargo tree 실패($manifest): ${r.stderr}');
  final refs = <CrateRef>{
    for (final l in const LineSplitter().convert(r.stdout as String))
      ?parseCargoTreeLine(l),
  }.toList()
    ..sort((a, b) => a.name == b.name ? a.version.compareTo(b.version) : a.name.compareTo(b.name));
  return [for (final c in refs) _load(c, registry)];
}

_Crate _load(CrateRef c, List<Directory> registry) {
  final dir = registry
      .map((d) => Directory('${d.path}${Platform.pathSeparator}${c.name}-${c.version}'))
      .firstWhere((d) => d.existsSync(), orElse: () => throw StateError('레지스트리에 원문이 없다: ${c.name} ${c.version}'));
  final texts = <String, String>{};
  final kinds = <String, LicenseKind>{};
  for (final f in dir.listSync().whereType<File>()) {
    final name = f.uri.pathSegments.last;
    if (!isLicenseFileName(name)) continue;
    texts[name] = _read(f);
    kinds[name] = classifyLicenseFile(name, texts[name]!);
  }
  // MIT는 "위 저작권 고지"를 함께 실어야 하므로 저작권 줄이 있는 MIT 파일이 있을 때만 MIT를 고른다(라이선스 감사).
  // 본문의 "the above copyright notice"가 아니라 "Copyright …"로 시작하는 줄을 찾는다.
  final copyrightLine = RegExp(r'^\s*(copyright|\(c\)|©)', caseSensitive: false, multiLine: true);
  final hasMit = kinds.entries.any((e) => e.value == LicenseKind.mit && copyrightLine.hasMatch(texts[e.key]!));
  final chosen = chooseLicenses(c.license, hasMitFile: hasMit);
  final files = {for (final n in selectLicenseFiles(chosen, kinds)) n: texts[n]!};
  for (final extra in _extraCrateFiles[c.name] ?? const <String>[]) {
    final f = File('${dir.path}${Platform.pathSeparator}${extra.replaceAll('/', Platform.pathSeparator)}');
    if (!f.existsSync()) throw StateError('${c.name}에 같이 컴파일되는 코드의 라이선스가 없다: $extra');
    files[extra] = _read(f);
  }
  final cargoToml = File('${dir.path}${Platform.pathSeparator}Cargo.toml');
  final toml = cargoToml.existsSync() ? _read(cargoToml) : '';
  String? field(String key) => RegExp('^$key\\s*=\\s*"([^"]+)"', multiLine: true).firstMatch(toml)?.group(1);
  final repo = field('repository');
  if (chosen.contains('MPL-2.0') && repo == null) throw StateError('MPL 크레이트의 소스 위치(repository)가 없다: ${c.name}');
  // 항목마다 프로젝트 주소를 둔다(Ableton Live의 Third-party License Information.txt처럼).
  final url = repo ?? field('homepage') ?? 'https://crates.io/crates/${c.name}';
  return _Crate(c, chosen, files, repo, url, kinds, texts);
}

String _read(File f) => utf8.decode(f.readAsBytesSync(), allowMalformed: true).replaceAll('\r\n', '\n');

/// 부록에 한 번만 실을 원문(Apache·MPL). 크레이트 이름 순으로 처음 나오는 파일을 쓴다.
String? _appendixText(List<_Crate> crates, LicenseKind kind, {String? preferName}) {
  for (final c in crates) {
    for (final e in c.kinds.entries) {
      if (e.value == kind && (preferName == null || e.key.toUpperCase() == preferName)) return c.texts[e.key];
    }
  }
  if (preferName != null) return _appendixText(crates, kind);
  return null;
}

void _section(StringBuffer b, String title) {
  b
    ..writeln()
    ..writeln(_band)
    ..writeln(title)
    ..writeln(_band)
    ..writeln();
}

void _crateEntry(StringBuffer b, _Crate c) {
  final expr = c.ref.license.isEmpty ? '(not stated in the package metadata; license file below)' : c.ref.license;
  final used = c.chosen.isEmpty ? '' : ' - used under ${c.chosen.join(' AND ')}';
  b
    ..writeln(_line)
    ..writeln('${c.ref.name} ${c.ref.version}')
    ..writeln(c.url)
    ..writeln('License: $expr$used');
  if (c.chosen.contains('Apache-2.0')) b.writeln('The Apache License 2.0 text is in Appendix A.');
  if (c.chosen.contains('MPL-2.0')) {
    b.writeln('The Mozilla Public License 2.0 text is in Appendix B. The Source Code Form of this component is '
        'available at ${c.repository} (version ${c.ref.version}). The Awesome uses it unmodified.');
  }
  for (final e in c.files.entries) {
    b
      ..writeln()
      ..writeln('[${e.key}]')
      ..writeln(e.value.trim());
  }
  b.writeln();
}

String _flutterNotices(Directory assets) {
  final z = File('${assets.path}${Platform.pathSeparator}NOTICES.Z');
  if (!z.existsSync()) throw StateError('Flutter 고지가 없다(빌드 뒤에 돌린다): ${z.path}');
  final text = utf8.decode(gzip.decode(z.readAsBytesSync()));
  if (text.trim().isEmpty) throw StateError('Flutter 고지가 비었다: ${z.path}');
  return text.replaceAll('\r\n', '\n');
}

/// three.js, WebView2 로더, Material Icons 글꼴, model-viewer(들어 있을 때). Apache 부록을 쓰면 true.
bool _otherFiles(StringBuffer b, Directory assets, String? webview2License) {
  final sep = Platform.pathSeparator;
  var apache = false;

  final js = Directory('${assets.path}${sep}assets${sep}js');
  if (js.existsSync()) {
    final names = [for (final f in js.listSync().whereType<File>()) f.uri.pathSegments.last]..sort();
    final three = File('${js.path}${sep}three.min.js');
    final head = three.existsSync() ? _read(three) : '';
    final copyright = RegExp(r'Copyright (\d{4}-\d{4}) Three\.js Authors').firstMatch(head)?.group(1);
    final revision = RegExp(r'REVISION\s*=\s*"(\d+)"').firstMatch(head)?.group(1);
    if (copyright == null) throw StateError('three.min.js에서 저작권 줄을 찾지 못했다');
    b
      ..writeln(_line)
      ..writeln('three.js${revision == null ? '' : ' r$revision'} and its example loaders '
          '(data/flutter_assets/assets/js: ${names.join(', ')})')
      ..writeln('https://github.com/mrdoob/three.js')
      ..writeln('License: MIT')
      ..writeln()
      ..writeln('Copyright $copyright Three.js Authors')
      ..writeln()
      ..writeln(_mitBody)
      ..writeln();
  }

  if (webview2License != null) {
    final f = File(webview2License);
    if (!f.existsSync()) throw StateError('WebView2 SDK 라이선스가 없다: $webview2License');
    b
      ..writeln(_line)
      ..writeln('Microsoft Edge WebView2 SDK loader (WebView2Loader.dll)')
      ..writeln('https://www.nuget.org/packages/Microsoft.Web.WebView2')
      ..writeln()
      ..writeln(_read(f).trim())
      ..writeln();
  }

  if (File('${assets.path}${sep}fonts${sep}MaterialIcons-Regular.otf').existsSync()) {
    apache = true;
    b
      ..writeln(_line)
      ..writeln('Material Icons font (data/flutter_assets/fonts/MaterialIcons-Regular.otf)')
      ..writeln('https://github.com/google/material-design-icons')
      ..writeln('Copyright Google LLC. License: Apache-2.0 (text in Appendix A).')
      ..writeln();
  }

  final mv = File('${assets.path}${sep}packages${sep}model_viewer_plus${sep}assets${sep}model-viewer.min.js');
  if (mv.existsSync()) {
    final blocks = <String>{
      for (final m in RegExp(r'/\*[*!]?[\s\S]*?\*/').allMatches(_read(mv)))
        if (m.group(0)!.contains('@license')) m.group(0)!.trim(),
    };
    b
      ..writeln(_line)
      ..writeln('<model-viewer> (data/flutter_assets/packages/model_viewer_plus/assets/model-viewer.min.js), '
          'distributed with the model_viewer_plus package')
      ..writeln('The file bundles the components below. Their notices, as found in the file:')
      ..writeln();
    for (final block in blocks) {
      b
        ..writeln(block)
        ..writeln();
    }
    b
      ..writeln('BSD-3-Clause license text (for the components above that name it):')
      ..writeln()
      ..writeln(_bsd3Body)
      ..writeln()
      ..writeln('MIT license text (for the components above that name it):')
      ..writeln()
      ..writeln(_mitBody)
      ..writeln();
  }
  return apache;
}

